C = '(@CommRingFreydPresentation_cat R)'
B = f'(Functor_oplax_cat WalkingArrow_cat {C})'

def migrate_freyd_remaining_consumer(name, original):
    if name not in SOURCES:
        return None
    spec = SOURCES[name]
    assert hashlib.sha256(original.encode()).hexdigest() == spec['sha256'], name
    text, count = re.subn(r'\bOp_cat(?=\s+\(@CommRingFreydPresentation_cat\s+R\))', 'TotalOp_cat', original)
    assert count == spec['initialOp'] and len(re.findall(r'\bOp_cat\b', original)) == count, name
    for pattern, replacement, key in (
        (r'\bFunctor_cat(?=\s+WalkingArrow_cat\s+\(@CommRingFreydPresentation_cat\s+R\))', 'Functor_oplax_cat', 'diagramCategory'),
        (r'\(Functor\s+WalkingArrow_cat\s+\(@CommRingFreydPresentation_cat\s+R\)\)', f'(Obj {B})', 'diagramCarrier'),
        (r'@Transf\s+WalkingArrow_cat\s+\(@CommRingFreydPresentation_cat\s+R\)', f'@Hom {B}', 'diagramHom'),
    ):
        text, count = re.subn(pattern, replacement, text)
        assert count == spec[key], (name, key)
    count = 0
    while hits := list(re.finditer(r'@tapp0_fapp0\s+WalkingArrow_cat\s+\(@CommRingFreydPresentation_cat\s+R\)', text)):
        m = hits[-1]
        cursor = m.end()
        args = []
        for _ in range(4):
            arg, cursor = _atom(text, cursor)
            args.append(arg)
        source, target, point, cell = args
        assert point in ('walking_arrow_src', 'walking_arrow_tgt'), name
        new = f'@fapp1_fapp0 {B} {C} (@diagram_oplax_evaluation_at_func WalkingArrow_cat {C} {point}) {source} {target} {cell}'
        text = text[:m.start()] + new + text[cursor:]
        count += 1
    assert count == spec['fixedPointAction'], name
    if name == 'examples/freyd_zero_cones.lp':
        text, count = re.subn(r'@hom_int\b', '@hom_int_view', text)
        assert count == 1, name
    return text
