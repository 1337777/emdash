#!/usr/bin/env python3
"""Finite strict 2-category controls for two mixed-family profile boundaries.

These are semantic countermodels, not a native library or omega construction.
One-cells are paths in a finite acyclic graph. Two-cells form the least local
preorder generated by the supplied parallel pairs and closed under whiskering.
"""
from itertools import product
import json


class Finite2:
    def __init__(self, objects, edges, generators):
        self.objects = tuple(objects)
        self.edges = edges
        self.paths = {(x, ()) for x in objects}
        while True:
            more = {(x, word + (name,)) for x, word in self.paths
                    for name, (s, _) in edges.items()
                    if self.target((x, word)) == s}
            if more <= self.paths:
                break
            self.paths |= more
        self.cells = {(p, p) for p in self.paths} | set(generators)
        assert all(p in self.paths and q in self.paths and p[0] == q[0]
                   and self.target(p) == self.target(q) for p, q in self.cells)
        while True:
            more = {(p, r) for p, q in self.cells for q1, r in self.cells if q == q1}
            for p, q in self.cells:
                for a in self.paths:
                    if self.target(a) == p[0]:
                        more.add((self.compose(p, a), self.compose(q, a)))
                    if self.target(p) == a[0]:
                        more.add((self.compose(a, p), self.compose(a, q)))
            if more <= self.cells:
                break
            self.cells |= more
        # Check units, associativity and interchange/monotonicity of the
        # locally posetal composition, not only the distinguishing pair.
        for p in self.paths:
            assert self.compose(p, (p[0], ())) == p
            assert self.compose((self.target(p), ()), p) == p
        for a, b, c in product(self.paths, repeat=3):
            if self.target(a) == b[0] and self.target(b) == c[0]:
                assert self.compose(c, self.compose(b, a)) == self.compose(self.compose(c, b), a)
        for (a, a1), (b, b1) in product(self.cells, repeat=2):
            if self.target(a) == b[0]:
                assert (self.compose(b, a), self.compose(b1, a1)) in self.cells

    def target(self, path):
        source, word = path
        return self.edges[word[-1]][1] if word else source

    def compose(self, after, before):
        assert self.target(before) == after[0]
        return before[0], before[1] + after[1]


def main():
    # A lax square between strict walking-arrow functors H and J.
    left = ('H0', ('e0', 'k'))
    right = ('H0', ('h', 'e1'))
    square = Finite2(('H0', 'H1', 'J0', 'J1'),
                    {'h': ('H0', 'H1'), 'k': ('J0', 'J1'),
                     'e0': ('H0', 'J0'), 'e1': ('H1', 'J1')}, [(left, right)])
    assert left != right and (left, right) in square.cells
    assert (right, left) not in square.cells

    # The existing ordinary internalization tapp1_at_transf(epsilon,0)
    # is Cat-valued. In the normal-lax square above it has components
    # selecting e0 at 0 and right=epsilon[p] at 1. Postcomposition by k
    # sends e0 to left. Strict naturality of this *internalization* would
    # require left=right and exclude this ordinary lax transformation.
    e0, e1 = ('H0', ('e0',)), ('H1', ('e1',))
    h, k = ('H0', ('h',)), ('J0', ('k',))
    assert square.compose(k, e0) == left
    assert square.compose(e1, h) == right
    internalization_is_strict = square.compose(k, e0) == right
    assert not internalization_is_strict

    # Reuse the square as a base-2-cell image E[alpha]:E[p]=>E[q].
    # For the source-u map in the proposed Homd ladder, evaluate its
    # f-naturality square at v=J1 and id_v. The two presheaf maps select
    # the distinct left/right objects of Hom_B(H0,J1). Thus an inner
    # default Cat-valued *strict* transfor cannot have these projections.
    # This is conditional on that curried target; it is not a no-go for
    # every mixed or dual coefficient, or a native family-admission proof.
    id_v = ('J1', ())
    index_then_source = square.compose(square.compose(id_v, e1), h)
    source_then_index = square.compose(square.compose(id_v, k), e0)
    assert index_then_source == right and source_then_index == left
    assert index_then_source != source_then_index
    # Precomposition by the strict transformation 0=>1 between point
    # selectors would be eval0=>eval1. Strict naturality on this lax square
    # would require equality of the two distinct paths above.

    # A separate ordinary-base control for the negative FAMILY parameter.
    # Over T(K), L:const(1)=>const(I) selects L[1]=0, L[0]=1 and 0->1.
    # Precomposition would need eval1=>eval0 over K. At H=id_I this would
    # give 1->0, which does not exist. Strict L excludes this input.
    interval = Finite2((0, 1), {'p': (0, 1)}, [])
    assert (0, ('p',)) in interval.paths
    assert not any(a[0] == 1 and interval.target(a) == 0 for a in interval.paths)

    r, s = ('a', ('r',)), ('a', ('s',))
    globe = Finite2(('a', 'b'), {'r': ('a', 'b'), 's': ('a', 'b')}, [(r, s)])
    # K has p=>q. For X:C2(K)->T(C), take X(p)=s, X(q)=r.
    # The reversed base cell q=>p maps to the existing r=>s.
    xp, xq = s, r
    assert (xq, xp) in globe.cells
    # E is constant at C, Y is constant at b. Hom(X(-),Y(-)) would send
    # p,q on id_b to s,r, respectively, requiring the nonexistent s=>r.
    assert (xp, xq) not in globe.cells
    # With X:T(K)->C instead, the same Hom action has the valid direction.
    assert (r, s) in globe.cells
    print(json.dumps({
        'raw_mapping_fibre': {'lax_square_exists': True,
                              'strict_precomposition_naturality': False},
        'cat_valued_strictness_internalization': {
            'strict_F_and_G': True,
            'normal_lax_epsilon_exists': True,
            'prescribed_tapp1_at_is_strict': internalization_is_strict,
            'uses_Pi_Sigma_Q_or_opposite': False},
        'homd_inner_strictness': {
            'base_2_cell_image_lax': True,
            'index_then_source': index_then_source,
            'source_then_index': source_then_index,
            'strict_index_naturality': False,
            'scope': 'prescribed u/v/f projections with a strict inner Cat-valued transfor'},
        'negative_family_parameter': {'lax_input_exists': True,
                                      'same_lax_output_exists': False},
        'shifted_op_section': {'strict_negative_input_exists': True,
                               'required_covariant_Hom_cell_exists': False,
                               'unshifted_contravariant_constant_section_control': True},
        'scope': 'finite strict 2-categories; no full omega replacement claimed',
    }, indent=2))


if __name__ == '__main__':
    main()
