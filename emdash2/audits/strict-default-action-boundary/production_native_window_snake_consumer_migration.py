def migrate_native_window_snake_consumer(name, original):
    if name not in SOURCES:
        return None
    spec = SOURCES[name]
    assert hashlib.sha256(original.encode()).hexdigest() == spec['sha256'], name
    text, count = re.subn(r'\bOp_cat(?=\s+C\b)', 'TotalOp_cat', original)
    assert count == spec['initialOp'] and len(re.findall(r'\bOp_cat\b', original)) == count, name
    text, count = re.subn(r'\bFunctor_cat(?=\s+WalkingArrow_cat\s+C\b)', 'Functor_oplax_cat', text)
    assert count == spec['diagramCategory'], name
    for head in ('diagram_family_at_func', 'diagram_family_transf', 'diagram_evaluation_at_func'):
        text, count = re.subn(r'\b' + head + r'\b', head.replace('diagram_family', 'diagram_oplax_family').replace('diagram_evaluation', 'diagram_oplax_evaluation'), text)
        assert count == spec[head], (name, head)
    text, count = re.subn(r'\bsym_transf_tapp0_transf\b', 'diagram_oplax_family_map_at', text)
    assert count == spec['sym_transf_tapp0_transf'], name
    if name == 'examples/product_diagonal_reindex_views.lp':
        old = 'assertnot [A B : Cat] (F : τ (Functor A B)) [x y z : τ (Obj A)]'
        assert text.count(old) == 1 and spec['strictFunctorAssertionFlip'] == 1
        text = text.replace(old, old.replace('assertnot', 'assert', 1))
        text = text.replace('// Independent ambient strictness boundaries remain unchanged.',
                            '// Public functors are now strict; the independent general-transfor boundary remains lax.')
    else:
        assert spec['strictFunctorAssertionFlip'] == 0
    if name == 'emdash3_2_product_diagonal_reindex_views.lp':
        text = text.replace('// postcomposition path; it imposes no strictness on Prod, Q or H.',
                            '// postcomposition path; it requires no additional profile beyond the default functors.')
        start = text.index('unif_rule\n')
        assert text[start:].count('unif_rule') == 1
        text = text[:start] + '// Existing whole-composition views supply the diagonal comparison; no extra unifier is needed.\n'
    return text
